const byId = new Map(SPECIES.map((s) => [s.id, s]));

export function getSpecies(id: string | null | undefined): Species | undefined {
  return id ? byId.get(id) : undefined;
}

export function searchSpecies(query: string): Species[] {
  const q = query.trim().toLowerCase();
  if (!q) return SPECIES;
  return SPECIES.filter(
    (s) =>
      s.commonName.toLowerCase().includes(q) ||
      s.scientificName.toLowerCase().includes(q) ||
      s.aliases.some((a) => a.includes(q)),
  );
}

/** Best catalog match for a scientific name from a plant-ID service. */
export function matchScientificName(name: string): Species | undefined {
  const n = name.toLowerCase();
  const exact = SPECIES.find((s) => s.scientificName.toLowerCase() === n);
  if (exact) return exact;
  const genus = n.split(' ')[0];
  return SPECIES.find((s) => s.scientificName.toLowerCase().split(' ')[0] === genus);
}
